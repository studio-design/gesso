// Hands the built site's heading anchors to lychee so it can confirm they are
// the ones GitHub emits.
//
// VitePress publishes GitHub's anchor spelling only because
// docs/.vitepress/github-slug.mjs overrides its slugifier. Two things can break
// that quietly: the override stops applying (a VitePress upgrade, a config
// regression), or a heading uses a character our rule gets wrong. Either way the
// Markdown links stay green while every deep link into the site 404s.
//
// Rather than re-implement GitHub's rules to check them — lychee's own algorithm
// has moved between releases, so any local model would drift — write one
// fragment link per built heading back at the Markdown it came from and let the
// existing `docs:links` run resolve them. lychee is then the single authority
// for what an anchor means, on both surfaces.
import { readFile, writeFile, access } from 'node:fs/promises'
import { glob } from 'node:fs/promises'
import { dirname, relative } from 'node:path'

const dist = 'docs/.vitepress/dist'
const probe = `${dist}/anchor-probe.md`

const exists = async (path) =>
  access(path).then(
    () => true,
    () => false
  )

const links = []

for await (const page of glob(`${dist}/**/*.html`)) {
  const source = `docs/${relative(dist, page).replace(/\.html$/, '.md')}`

  // 404.html and anything else the theme renders without a Markdown source.
  if (!(await exists(source))) {
    continue
  }

  const html = await readFile(page, 'utf8')

  for (const [, id] of html.matchAll(
    /<h[1-6] id="([^"]*)"[^>]*>[\s\S]*?<a class="header-anchor"/g
  )) {
    links.push(`- [${source}](${relative(dirname(probe), source)}#${id})`)
  }
}

if (links.length === 0) {
  throw new Error(`No headings found under ${dist} — run \`npm run docs:build\` first`)
}

await writeFile(
  probe,
  `# Built heading anchors\n\n` +
    `Generated by scripts/emit-anchor-probe.mjs. Every link below is an anchor\n` +
    `the site publishes, pointed back at the Markdown heading it came from, so\n` +
    `\`npm run docs:links\` fails if the two ever disagree.\n\n` +
    `${links.join('\n')}\n`
)

console.log(`Wrote ${links.length} built heading anchors to ${probe} for lychee to resolve.`)
